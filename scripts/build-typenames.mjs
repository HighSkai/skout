// Generates server/src/engine/typeNames.generated.ts from the `types:` section of
// Skript's default.lang: the English names Skript uses for its types in error
// messages ("a text", "an integer", "a boolean (yes/no)").
//
// Development only, like build-dumps.mjs: run it with `npm run dumps` when a new
// Skript version is released, then commit the result.
//
// The data comes from SkriptLang/Skript (GPL-3.0).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const LANG_VERSION = '2.17.1';

/** Noun#getPlural: `stem¦plural`, `stem¦singular¦plural` or `stem¦singular¦plural¦suffix`. */
function noun(text) {
  const parts = text.split('¦');
  switch (parts.length) {
    case 1:
      return [parts[0], parts[0]];
    case 2:
      return [parts[0], parts[0] + parts[1]];
    case 3:
      return [parts[0] + parts[1], parts[0] + parts[2]];
    case 4:
      return [parts[0] + parts[1] + parts[3], parts[0] + parts[2] + parts[3]];
    default:
      throw new Error(`unexpected noun: ${text}`);
  }
}

export function parseTypeNames(lang) {
  const names = {};
  let inTypes = false;
  for (const raw of lang.split(/\r?\n/)) {
    if (/^\S/.test(raw)) {
      inTypes = /^types:\s*$/.test(raw);
      continue;
    }
    if (!inTypes) continue;
    const m = /^\t([a-z0-9]+):\s*(.+?)\s*$/.exec(raw);
    if (!m) continue;
    let value = m[2];
    let article = 'a';
    const at = /\s*@(\S+)$/.exec(value);
    if (at) {
      article = at[1] === 'an' ? 'an' : at[1] === 'a' ? 'a' : '';
      value = value.slice(0, at.index);
    }
    const [singular, plural] = noun(value);
    names[m[1]] = [singular, plural, article];
  }
  return names;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('build-typenames.mjs')) {
  const url = `https://raw.githubusercontent.com/SkriptLang/Skript/${LANG_VERSION}/src/main/resources/lang/default.lang`;
  const response = await fetch(url, { headers: { 'user-agent': 'skout-build-dumps' } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const names = parseTypeNames(await response.text());
  const count = Object.keys(names).length;
  if (count < 100) throw new Error(`only ${count} type names found in ${url}`);
  const body = Object.entries(names)
    .map(([id, [s, p, a]]) => `  ${JSON.stringify(id)}: [${JSON.stringify(s)}, ${JSON.stringify(p)}, ${JSON.stringify(a)}],`)
    .join('\n');
  const file = join(import.meta.dirname, '..', 'server', 'src', 'engine', 'typeNames.generated.ts');
  writeFileSync(
    file,
    `// Generated by scripts/build-typenames.mjs from Skript ${LANG_VERSION}'s default.lang (GPL-3.0). Do not edit.\n` +
      '// codename: [singular, plural, indefinite article]\n' +
      `export const TYPE_NAMES: Readonly<Record<string, readonly [string, string, string]>> = {\n${body}\n};\n`,
  );
  console.log(`${file}: ${count} type names`);
}
