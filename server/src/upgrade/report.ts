/** Renders an upgrade check as a Markdown report. */
import type { Finding, FindingKind, UpgradeResult } from './check';

const SECTIONS: { title: string; intro: string; kinds: FindingKind[] }[] = [
  {
    title: 'Will break',
    intro: 'Lines that use syntax the target version no longer has. Skript will refuse to load them.',
    kinds: ['removed'],
  },
  {
    title: 'Functions that will fail to register',
    intro: "Skript reports these when the script loads, and every call to the function then fails too.",
    kinds: ['function-type', 'function-clash', 'function-removed'],
  },
  {
    title: 'Deprecated',
    intro: 'Still works, but marked for removal.',
    kinds: ['deprecated'],
  },
  {
    title: 'Behaviour changes',
    intro: "The syntax still exists but works differently. From Skript's release notes.",
    kinds: ['behaviour'],
  },
];

export interface ReportOptions {
  /** A Markdown link target for a finding, e.g. `../scripts/shop.sk#L12`. */
  readonly linkFor: (uri: string, line: number) => string;
  /** A short display path for a script. */
  readonly nameFor: (uri: string) => string;
  readonly date: string;
  readonly skoutVersion: string;
}

export function renderReport(result: UpgradeResult, options: ReportOptions): string {
  const out: string[] = [];
  const count = (kinds: FindingKind[]) => result.findings.filter((f) => kinds.includes(f.kind)).length;

  out.push(`# Upgrade check: ${result.from} → ${result.to}`);
  out.push('');
  out.push(`Generated by Skout ${options.skoutVersion} on ${options.date}. Checked ${result.scripts} script${result.scripts === 1 ? '' : 's'} and ${result.linesChecked} lines of syntax.`);
  out.push('');
  out.push('| | Lines |');
  out.push('|---|---:|');
  for (const section of SECTIONS) out.push(`| ${section.title} | ${count(section.kinds)} |`);
  out.push('');
  if (result.findings.length === 0) {
    out.push(`**Nothing to change.** No line in your scripts uses syntax that ${result.to} removes, deprecates or changes, as far as Skout can tell (see [How this was checked](#how-this-was-checked)).`);
    out.push('');
  }

  for (const section of SECTIONS) {
    const findings = result.findings.filter((f) => section.kinds.includes(f.kind));
    if (findings.length === 0) continue;
    out.push(`## ${section.title} (${findings.length})`);
    out.push('');
    out.push(section.intro);
    out.push('');
    for (const f of findings) out.push(...renderFinding(f, options));
    out.push('');
  }

  const { removed, deprecated } = result.diff;
  if (removed.length > 0 || deprecated.length > 0) {
    out.push(`## All syntax ${result.to} removes or deprecates`);
    out.push('');
    out.push('Including syntax your scripts do not use, for reference.');
    out.push('');
    out.push('<details><summary>Show the list</summary>');
    out.push('');
    for (const r of removed) out.push(`- **Removed** ${r.kind} *${escape(r.name)}*: ${r.patterns.map((p) => `\`${p}\``).join(', ')}`);
    for (const d of deprecated) out.push(`- **Deprecated** ${d.kind} *${escape(d.name)}*`);
    out.push('');
    out.push('</details>');
    out.push('');
  }

  out.push('## How this was checked');
  out.push('');
  out.push(`Each line was matched against the syntax of ${result.from} and of ${result.to}, using a port of Skript's own pattern matcher. A line that matched before but matches nothing after is reported as breaking. Function signatures were checked against the types and built-in functions of the target, and known behaviour changes come from Skript's release notes.`);
  out.push('');
  out.push(`Limits: Skout cannot parse the expressions inside a pattern's \`%slots%\`, so a removed expression is only found when its wording is distinctive. Addon syntax is only checked if its syntax dump is loaded (\`skout.syntaxDumps\`). Test on a copy of your server before upgrading the live one.`);
  out.push('');
  return out.join('\n');
}

function renderFinding(f: Finding, options: ReportOptions): string[] {
  const lines = [`- **[${escape(options.nameFor(f.uri))}:${f.line + 1}](${options.linkFor(f.uri, f.line)})** \`${f.lineText.replace(/`/g, "'")}\``];
  lines.push(`  - ${f.message}${f.link ? ` ([release notes](${f.link}))` : ''}`);
  if (f.suggestion) lines.push(`  - ↳ ${f.suggestion}`);
  return lines;
}

function escape(text: string): string {
  return text.replace(/([*_[\]|])/g, '\\$1');
}
